  themes.find((t) => t.id === id);

export const getThemesByReligion = (religion: string): Theme[] =>
  themes.filter((t) => t.religion === religion || t.religion === "universal");

export const getFreeThemes = (): Theme[] =>
  themes.filter((t) => !t.premium && t.is_active);

export const getPremiumThemes = (): Theme[] =>
  themes.filter((t) => t.premium && t.is_active);
